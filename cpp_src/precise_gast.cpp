// GAST (Greenwich Apparent Sidereal Time) calculation using the
// IAU 2000A nutation model with Equation of the Origins.

#include "precise_gast.h"
#include <cmath>

// --- Main Calculation Function ---
double PreciseGastCalculator::calculate_gast_radians(double jd_ut1, double jd_tdb) {
    const long double t = (static_cast<long double>(jd_tdb) - J2000) / DAYS_PER_CENTURY;

    // Step 1: Calculate Earth Rotation Angle (ERA) from UT1.
    const double era_rad = calculate_era(jd_ut1);

    // Step 2: Calculate the Equation of the Origins (EO) for precession.
    const double eo_rad = calculate_equation_of_origins(t);

    // Step 3: Greenwich Mean Sidereal Time is ERA minus the EO.
    const double gmst_rad = era_rad - eo_rad;

    // Step 4: Calculate the Equation of the Equinoxes (EofE) for nutation.
    const auto args = calculate_fundamental_arguments(t);
    double d_psi_rad, d_eps_rad;
    calculate_nutation(t, args, d_psi_rad, d_eps_rad);
    const double epsilon_a_rad = calculate_mean_obliquity(t);
    const double eofe_rad = calculate_eofe(d_psi_rad, epsilon_a_rad, args[4]);

    // Step 5: Final GAST is GMST + EofE.
    double gast_rad = gmst_rad + eofe_rad;

    // Normalize to [0, 2π)
    gast_rad = fmod(gast_rad, TWOPI);
    if (gast_rad < 0) {
        gast_rad += TWOPI;
    }
    return gast_rad;
}

// --- Helper Functions ---

double PreciseGastCalculator::calculate_equation_of_origins(long double t) {
    const long double t2 = t * t, t3 = t2 * t, t4 = t3 * t, t5 = t4 * t;
    const long double eo_arcsec = -0.014506L - 4612.156534L * t - 1.3915817L * t2 + 0.00000044L * t3 + 0.000029956L * t4 + 0.0000000368L * t5;
    return static_cast<double>(eo_arcsec * ASEC_TO_RAD);
}

void PreciseGastCalculator::calculate_nutation(long double t, const std::vector<long double>& args, double& d_psi_rad, double& d_eps_rad) {
    long double d_psi_accumulator = 0.0L;
    long double d_eps_accumulator = 0.0L;
    for (const auto& term : NUTATION_SERIES) {
        long double angle = term.nl * args[0] + term.nlp * args[1] + term.nf * args[2] + term.nd * args[3] + term.nom * args[4];
        d_psi_accumulator += (term.ps + term.pc * t) * sinl(angle);
        d_eps_accumulator += (term.es + term.ec * t) * cosl(angle);
    }
    // Coefficients are in units of 0.1 microarcseconds. The correct scaling factor is 1e-7.
    d_psi_rad = static_cast<double>(d_psi_accumulator * 1e-7L * ASEC_TO_RAD);
    d_eps_rad = static_cast<double>(d_eps_accumulator * 1e-7L * ASEC_TO_RAD);
}

double PreciseGastCalculator::calculate_era(double jd_ut1) {
    const double term = 0.7790572732640 + 1.00273781191135448 * (jd_ut1 - J2000);
    return fmod(TWOPI * term, TWOPI);
}

std::vector<long double> PreciseGastCalculator::calculate_fundamental_arguments(long double t) {
    std::vector<long double> args(5); const long double t2=t*t, t3=t2*t;
    args[0] = fmod(485868.249036L + 1717915923.2178L * t + 31.8792L * t2 + 0.051635L * t3, 1296000.0L) * ASEC_TO_RAD;
    args[1] = fmod(1287104.79305L + 129596581.0481L * t - 0.5532L * t2 + 0.000136L * t3, 1296000.0L) * ASEC_TO_RAD;
    args[2] = fmod(335779.526232L + 1739527262.8478L * t - 12.7512L * t2 - 0.001037L * t3, 1296000.0L) * ASEC_TO_RAD;
    args[3] = fmod(1072260.70369L + 1602961601.2090L * t - 6.3706L * t2 + 0.006593L * t3, 1296000.0L) * ASEC_TO_RAD;
    args[4] = fmod(450160.398036L - 6962890.5431L * t + 7.4722L * t2 + 0.007702L * t3, 1296000.0L) * ASEC_TO_RAD;
    return args;
}

double PreciseGastCalculator::calculate_mean_obliquity(long double t) {
    const long double p_arcsec = 84381.406L - 46.836769L * t - 0.0001831L * t*t + 0.00200340L * t*t*t - 5.76e-7L * t*t*t*t - 4.34e-8L * t*t*t*t*t;
    return static_cast<double>(p_arcsec * ASEC_TO_RAD);
}

double PreciseGastCalculator::calculate_eofe(double d_psi_rad, double epsilon_a_rad, double mean_asc_node_rad) {
    const double term1 = d_psi_rad * cos(epsilon_a_rad);
    const double term2 = (0.0023528 * sin(mean_asc_node_rad)) * static_cast<double>(ASEC_TO_RAD);
    const double term3 = (0.0000854 * sin(2.0 * mean_asc_node_rad)) * static_cast<double>(ASEC_TO_RAD);
    return term1 + term2 + term3;
}

